"""Adapt-1 (production API) on XLand-MiniGrid through macro-actions (xland_macro.py), online: learning on, exploration on.

usage: xland_run_adapt1.py TIER ARM FIRST_RULESET N_RULESETS SEED OUT_DIR [JOURNAL_DIR]
  TIER  trivial | small | medium (position-free rulesets generated by gen_rulesets.py)
  ARM   retained   one Domain for the whole run; each ruleset is one episode (K trials); state carries across rulesets
        tasklocal  a fresh Domain per ruleset, deleted after its K trials (zero-start task-local learning, docs schedule)
Declaration: the docs' recommended sequential-learning declaration with task fields: context = the macro controller's
decision features (slot present/held/known, slot class codes, holding, trial and step fractions, last macro outcome);
policies = pick/goto/put for each of the 9 class slots plus drop (28), policy_features = operation one-hot and slot index;
reward = the trial reward attributed to the macro that ended the trial (bounds [0, 1]); sequential learning with
eligibility traces (discount 0.9, n_step 6); TCP over the scalar summary inputs (lag 6); latent belief on.
Online loop: one query and one decision-linked feedback per macro. Abstention / illegal selection -> a random applicable
macro is executed and counted as a fallback. Every Domain is deleted at the end with a 404 readback.
"""
import sys, json, time, random
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE)); sys.path.insert(0, str(HERE.parent / 'common'))
import numpy as np
import xland_macro as X
from client import Client, Ambiguous, ApiError, new_id

TIER, ARM, FIRST, NRS, SEED, OUT = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5]), Path(sys.argv[6])
JDIR = Path(sys.argv[7]) if len(sys.argv) > 7 else OUT
BASE = 'https://rei-neuroadapt-api.reilabs.org/api/v1'
OUT.mkdir(parents=True, exist_ok=True); JDIR.mkdir(parents=True, exist_ok=True)
tag = f'xland-{TIER}-{ARM}-s{SEED}'
bench = X.load_tier(TIER); env = X.MacroXLand()
REL = 'macro'
POLICIES = X.MacroXLand.policy_names()   # pick_i / goto_i / put_i for 10 slots, drop (31)
FIELDS = None


def features(e):
    v = e.context()
    for i, c in enumerate(e.slots):
        v[f'slot{i}_tile'] = (c[0] / 12.0) if c else 0.0
        v[f'slot{i}_color'] = (c[1] / 11.0) if c else 0.0
    return v


def declaration(did):
    hyps = []
    for p in POLICIES:
        if p == 'drop':
            pf = {'op_pick': 0.0, 'op_goto': 0.0, 'op_put': 0.0, 'op_drop': 1.0, 'slot': -1.0}
        else:
            op, i = p.rsplit('_', 1)
            pf = {'op_pick': float(op == 'pick'), 'op_goto': float(op == 'goto'), 'op_put': float(op == 'put'), 'op_drop': 0.0, 'slot': float(i)}
        hyps.append({'name': f'macro {p}', 'relation': REL, 'policy': p, 'policy_features': pf, 'when': [], 'predicts': ['trial reward'], 'falsified_by': [], 'weight': 1.0})
    scalar_inputs = ['holding', 'trial_frac', 'steps_frac', 'macros_in_trial', 'last_success', 'last_reward']
    learning = {
        'enabled': True,
        'context': {'feature_paths': [f'values.{k}' for k in FIELDS], 'event_types': ['state'], 'max_samples': 4096},
        'reward': {'aggregation': 'weighted_mean', 'components': [{'field': 'values.step_reward', 'goal': 'maximize', 'min': 0.0, 'max': 1.0, 'weight': 1.0, 'required': True}]},
        'policy': {'decay_half_life_seconds': 0.0, 'transfer_strength': 0.0, 'action_transfer_strength': 0.05, 'min_context_observations': 4,
                   'model_max_weight': 0.45, 'model_ood_threshold': 0.75, 'ood_confidence_penalty': 0.5, 'exploration_mode': 'auto',
                   'exploration_strength': 1.0, 'minimum_expected_reward': 0.0, 'minimum_confidence': 0.0, 'require_credible_dominance': False,
                   'dominance_margin': 0.0, 'abstain_on_ood': False},
        'credit_assignment': {'mode': 'eligibility_trace', 'discount': 0.9, 'neutral_reward': 0.0, 'minimum_weight': 0.01, 'delay_path': 'values.delay_steps'},
        'latent_belief': {'enabled': True, 'max_regimes': 8, 'novelty_threshold': 0.55, 'temperature': 0.25, 'change_point_threshold': 0.55,
                          'change_point_patience': 3, 'historical_regime_weight': 0.05},
        'training': {'enabled': True, 'min_samples': 64, 'retrain_interval': 16, 'dimensions': 96, 'epochs': 100, 'learning_rate': 0.04},
        'sequential': {'enabled': True, 'episode_path': 'metadata.episode_id', 'step_path': 'metadata.step', 'next_context_path': 'values.next_state',
                       'reward_path': 'values.step_reward', 'terminal_path': 'values.terminal', 'discount': 0.9, 'n_step': 6, 'minimum_episodes': 10,
                       'minimum_validation_skill': 0.1, 'target_sync_interval': 10, 'conservative_weight': 0.05},
        'temporal_context': {'enabled': True, 'episode_path': 'metadata.episode_id', 'step_path': 'metadata.step', 'input_paths': [f'values.{k}' for k in scalar_inputs], 'maximum_lag': 6},
    }
    return {'domain_id': did, 'session_id': 'ignored', 'description': f'XLand-MiniGrid {TIER} macro-actions, {ARM} arm, seed {SEED}',
            'schema': {'entities': ['agent', 'world'], 'relations': [REL], 'signals': FIELDS + ['step_reward'], 'event_types': ['state', 'feedback']},
            'hypotheses': hyps, 'learning': learning}


api = Client(JDIR / f'journal-{tag}.jsonl.xz', base=BASE)


def create_domain(decl):
    """POST /domains with reconciliation: an ambiguous failure (connection reset, 5xx) is resolved by reading the Domain
    back; if it exists the creation counted, otherwise the request is retried."""
    for attempt in range(8):
        try:
            return api.post('/domains', decl)
        except (Ambiguous, ApiError) as e:
            if isinstance(e, ApiError) and e.code < 500:
                raise
            time.sleep(min(60, 5 * (attempt + 1)))
            try:
                got = api.call('GET', f"/domains/{decl['domain_id']}", None, mutation=False)
                if got:
                    return got
            except ApiError as g:
                if g.code != 404:
                    continue
    raise SystemExit('could not create Domain after 8 attempts')


ep_log = open(OUT / f'episodes-{tag}.jsonl', 'a', buffering=1)
diag_log = open(OUT / f'diagnostics-{tag}.jsonl', 'a', buffering=1)
stats = {'macros': 0, 'fallbacks': 0, 'not_applied': 0, 'query_retries': 0, 'domains': 0}
t0 = time.time(); rng = random.Random(SEED)


def query(did, values, ep_id, step, diag):
    body = {'session_id': 'ignored', 'question': 'Choose the next macro-action.', 'relation': REL,
            'context': {'event_type': 'state', 'values': values, 'metadata': {'episode_id': ep_id, 'step': step}},
            'allow_exploration': True, 'selection_mode': 'auto',
            'return_fields': (['selection', 'decision_id', 'ranked_hypotheses', 'learning_state', 'latent_belief'] if diag else ['selection', 'decision_id'])}
    for attempt in range(3):
        try:
            return api.post(f'/domains/{did}/query', body)
        except (Ambiguous, ApiError) as e:
            if isinstance(e, ApiError) and e.code < 500:
                raise
            stats['query_retries'] += 1; time.sleep(2 * (attempt + 1))
    raise SystemExit(f'query failed 3 times at {ep_id} step {step}')



def applicable(e):
    present = set(e.classes_present()); pocket = e.pocket(); out = []
    for i, c in enumerate(e.slots):
        if c is None or c not in present:
            continue
        out.append(f'goto_{i}'); out.append(f'pick_{i}' if pocket[0] == 0 else f'put_{i}')
    if pocket[0] != 0:
        out.append('drop')
    return out or ['drop']


def run_ruleset(did, idx, decl_written):
    global FIELDS
    rs = bench.get_ruleset(idx)
    try:
        env.start(rs, SEED * 100000 + idx)
    except ValueError as e:          # too many initial classes for the fixed policy set: skipped and recorded
        ep_log.write(json.dumps({'ruleset': idx, 'skipped': str(e)}) + '\n'); return None
    ep_id = f'{tag}-r{idx:05d}'; step = 0; macro_log = []
    while not env.episode_done():
        values = features(env)
        diag = (step == 0 and idx % 25 == 0)
        q = query(did, values, ep_id, step, diag)
        sel = (q.get('selection') or {}).get('selected_policy')
        legal = applicable(env)
        if sel in legal:
            executed = sel; fb = False
        else:
            # abstention or an inapplicable macro (class absent / nothing held): the integration enforces eligibility
            # (docs: validate the returned policy against the current permitted set) and executes a random applicable macro
            executed = rng.choice(legal); fb = True; stats['fallbacks'] += 1; stats['inapplicable'] = stats.get('inapplicable', 0) + int(sel in POLICIES)
        trial_before = env.trial
        r, ok, nprim = env.macro(executed)
        done = env.episode_done()
        nxt = features(env)
        res = api.feedback(did, {'session_id': 'ignored', 'outcome': 'success' if r > 0 else 'neutral', 'feedback_kind': 'execution', 'relation': REL,
                             'policy': executed, 'decision_id': q.get('decision_id'),
                             'values': {'step_reward': float(r), 'next_state': {'values': nxt}, 'terminal': bool(done), 'delay_steps': 0},
                             'metadata': {'episode_id': ep_id, 'step': step}}, stats)
        if res.get('reconciled') != 'applied' and (res.get('credit_assignment') or {}).get('contextual_learning_applied') is not True:
            stats['not_applied'] += 1
        if diag:
            ls = (q.get('learning_state') or {}).get('subsystems') or {}
            diag_log.write(json.dumps({'ruleset': idx, 'selected': sel, 'selected_by': (q.get('selection') or {}).get('selected_by'), 'latent': q.get('latent_belief'),
                                       'feedback_policy': (ls.get('feedback_policy') or {}).get('sample_count'), 'sequential': ls.get('sequential') or ls.get('sequential_policy'),
                                       'subsystems': sorted(ls)}) + '\n')
        macro_log.append([executed, round(r, 4), int(ok), nprim, int(fb)])
        step += 1; stats['macros'] += 1
        if step > 12 * env.K + 5:
            break
    goal, rules = X.decode_ruleset(rs)
    row = {'ruleset': idx, 'trial_rewards': list(env.trial_rewards) + [0.0] * (env.K - len(env.trial_rewards)), 'macros': step, 'prims': env.prims_total,
           'fallbacks': sum(m[4] for m in macro_log), 'goal_type': goal['type'], 'n_rules': len(rules), 'n_objects': env.n_init, 'macro_log': macro_log,
           'elapsed_s': round(time.time() - t0, 1), 'api_calls': api.calls}
    ep_log.write(json.dumps(row) + '\n')
    return row


# establish the feature list from one ruleset
env.start(bench.get_ruleset(FIRST), 0); FIELDS = sorted(features(env).keys())
summary = {'tier': TIER, 'arm': ARM, 'seed': SEED, 'first_ruleset': FIRST, 'n_rulesets': NRS, 'domains': []}
try:
    did = None
    if ARM == 'retained':
        did = new_id(f'xl-{TIER[:3]}-ret-s{SEED}'); decl = declaration(did); echo = create_domain(decl); stats['domains'] += 1
        (OUT / f'declaration-{tag}.json').write_text(json.dumps(decl, indent=1)); (OUT / f'echo-{tag}.json').write_text(json.dumps(echo.get('learning'), indent=1))
    for idx in range(FIRST, FIRST + NRS):
        if ARM == 'tasklocal':
            did = new_id(f'xl-{TIER[:3]}-tl-s{SEED}-r{idx}'); decl = declaration(did)
            (OUT / f'live-{tag}.json').write_text(json.dumps({'domain_id': did, 'ruleset': idx}))   # for cleanup if the process is lost
            echo = create_domain(decl); stats['domains'] += 1
            if idx == FIRST:
                (OUT / f'declaration-{tag}.json').write_text(json.dumps(decl, indent=1)); (OUT / f'echo-{tag}.json').write_text(json.dumps(echo.get('learning'), indent=1))
        row = run_ruleset(did, idx, True)
        if row is None:
            if ARM == 'tasklocal':
                d = api.delete_domain(did); summary['domains'].append({'ruleset': idx, 'domain_id': did, 'readback': d['readback'], 'skipped': True}); did = None
            continue
        if idx % 10 == 0:
            print(f'{tag} ruleset {idx}: trials {[round(x, 2) for x in row["trial_rewards"]]} macros {row["macros"]} calls {api.calls} {time.time() - t0:.0f}s', flush=True)
        if ARM == 'tasklocal':
            d = api.delete_domain(did); summary['domains'].append({'ruleset': idx, 'domain_id': did, 'readback': d['readback']}); did = None
        if stats['macros'] > 50 and stats['not_applied'] > 0.01 * stats['macros']:
            raise SystemExit(f'abort: {stats["not_applied"]} of {stats["macros"]} feedbacks not applied')
    outcome = 'completed'
except SystemExit as e:
    outcome = f'aborted: {e}'
finally:
    if did is not None:
        d = api.delete_domain(did); summary['domains'].append({'domain_id': did, 'readback': d['readback']})
    summary.update({'outcome': locals().get('outcome', 'crashed'), 'stats': stats, 'api_calls': api.calls, 'wall_s': round(time.time() - t0)})
    (OUT / f'summary-{tag}.json').write_text(json.dumps(summary, indent=1)); api.close()
    print(json.dumps({k: v for k, v in summary.items() if k != 'domains'}))
